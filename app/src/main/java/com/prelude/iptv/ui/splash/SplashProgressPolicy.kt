package com.prelude.iptv.ui.splash

/**
 * Πόσο γεμάτη είναι η μπάρα της εισαγωγής.
 *
 * ΤΟ ΠΡΟΒΛΗΜΑ: μια μπάρα δεμένη ΑΠΕΥΘΕΙΑΣ στην πραγματική πρόοδο φαίνεται
 * χαλασμένη. Η φόρτωση ενός καταλόγου δεν είναι ομαλή — μένει στο 0% όσο ανοίγει
 * η σύνδεση, πηδά στο 60% όταν έρθει το σώμα της απάντησης, κολλά στο 60% όσο
 * γίνεται το parsing, και τελειώνει απότομα. Ο χρήστης δεν βλέπει «πρόοδο»·
 * βλέπει μια μπάρα που παγώνει και μετά τινάζεται.
 *
 * ΤΟ ΑΝΤΙΘΕΤΟ ΕΙΝΑΙ ΧΕΙΡΟΤΕΡΟ: μια μπάρα με σταθερό χρόνο δύο δευτερολέπτων
 * είναι ψέμα. Όταν η λίστα θέλει δώδεκα, φτάνει στο 100% και μένει εκεί να
 * κοροϊδεύει· όταν θέλει μισό, καθυστερεί τον χρήστη χωρίς λόγο. Ο χρήστης το
 * καταλαβαίνει, και τότε δεν εμπιστεύεται καμία μπάρα της εφαρμογής.
 *
 * ΤΡΕΙΣ ΚΑΝΟΝΕΣ, ΟΛΟΙ ΔΟΚΙΜΑΣΜΕΝΟΙ ΕΔΩ:
 *
 * 1. **Δεν γυρίζει ποτέ πίσω.** Μια μπάρα που μικραίνει σημαίνει «ό,τι έκανα ως
 *    τώρα χάθηκε», και δεν είναι αυτό που συνέβη — απλώς άλλαξε το στάδιο.
 * 2. **Όταν δεν ξέρουμε, σέρνεται και δεν φτάνει.** Σε στάδια χωρίς ποσοστό
 *    (parsing, ταξινόμηση) πλησιάζει ασυμπτωτικά το [CREEP_CEILING] χωρίς να το
 *    περνά. Δείχνει ζωντανή χωρίς να υπόσχεται τέλος.
 * 3. **Το 100% σημαίνει τελείωσε.** Μόνο η πραγματική ολοκλήρωση το δίνει.
 */
object SplashProgressPolicy {

    /**
     * Πόσο ψηλά φτάνει μόνη της όταν δεν υπάρχει ποσοστό.
     *
     * 0,9 και όχι 0,99: πρέπει να μένει ορατός χώρος, ώστε το τελικό γέμισμα να
     * φαίνεται σαν ολοκλήρωση και όχι σαν στρογγυλοποίηση.
     */
    const val CREEP_CEILING = 0.90f

    /**
     * Πόσο κλείνει την απόσταση προς το ταβάνι σε κάθε βήμα.
     *
     * Σταθερό ποσοστό της ΑΠΟΣΤΑΣΗΣ, όχι σταθερό βήμα: έτσι τρέχει στην αρχή,
     * όπου δεν ξέρει τίποτα, και επιβραδύνει όσο πλησιάζει — ακριβώς η αίσθηση
     * που έχει ο χρήστης για μια δουλειά που «κοντεύει».
     */
    private const val CREEP_RATE = 0.06f

    /**
     * Πόσο γρήγορα προλαβαίνει την πραγματική τιμή όταν αυτή είναι γνωστή.
     *
     * Δεν πηδά κατευθείαν: ένα άλμα από 12% σε 74% δεν διαβάζεται ως πρόοδος,
     * διαβάζεται ως σφάλμα.
     */
    private const val CATCH_UP_RATE = 0.18f

    /**
     * Ελάχιστος χρόνος εμφάνισης, σε χιλιοστά.
     *
     * Όσο κρατά η σύνθεση του «+». Μια εισαγωγή που εμφανίζεται και φεύγει σε
     * 200ms δεν είναι γρήγορη — είναι μια αναλαμπή που μοιάζει με σφάλμα.
     */
    const val MIN_VISIBLE_MS = 2_600L

    /**
     * Πάνω όριο: μετά από αυτό φεύγει ό,τι κι αν κάνει ο πάροχος.
     *
     * Η φόρτωση ΔΕΝ διακόπτεται — ανήκει στο ViewModel και συνεχίζει από πίσω. Το
     * μόνο που φεύγει είναι η επίστρωση, ώστε ο χρήστης να δει την εφαρμογή με τον
     * κανονικό της δείκτη φόρτωσης αντί για ένα λογότυπο που δεν εξηγεί τίποτα.
     */
    const val MAX_VISIBLE_MS = 8_000L

    /**
     * Χρόνος για να προλάβει η μπάρα να φτάσει οπτικά στο τέρμα.
     *
     * Ζει ΕΔΩ και όχι ως `delay(320)` μέσα στην οθόνη: είναι μέρος της απάντησης
     * «πότε φεύγει», και μια σταθερά κρυμμένη σε ένα effect δεν φαίνεται όταν
     * κάποιος διαβάζει τους κανόνες.
     */
    private const val SETTLE_MS = 320L

    /**
     * Το επόμενο βήμα της μπάρας.
     *
     * @param shown τι δείχνει τώρα (0..1)
     * @param real η πραγματική πρόοδος, ή null αν το στάδιο δεν τη γνωρίζει
     * @param finished η φόρτωση ολοκληρώθηκε
     */
    fun next(shown: Float, real: Float?, finished: Boolean): Float {
        val current = shown.coerceIn(0f, 1f)
        if (finished) return 1f

        val target = when {
            real == null -> CREEP_CEILING
            else -> real.coerceIn(0f, 1f).coerceAtMost(CREEP_CEILING)
        }
        if (target <= current) return current

        val rate = if (real == null) CREEP_RATE else CATCH_UP_RATE
        val stepped = current + (target - current) * rate
        // Χωρίς αυτό, η ασυμπτωτική προσέγγιση σταματά να είναι ορατή κάτω από
        // την ακρίβεια του float και η μπάρα φαίνεται παγωμένη λίγο πριν το τέλος.
        return (stepped + MIN_STEP).coerceAtMost(target)
    }

    /** Το ελάχιστο ορατό βήμα ανά καρέ. */
    private const val MIN_STEP = 0.0008f

    /**
     * Πόσα χιλιοστά ακόμη πρέπει να μείνει η εισαγωγή. `0` = φύγε τώρα.
     *
     * ΓΙΑΤΙ ΕΠΙΣΤΡΕΦΕΙ ΑΝΑΜΟΝΗ ΚΑΙ ΟΧΙ «ΝΑΙ/ΟΧΙ»: με ένα `canDismiss` η οθόνη
     * πρέπει να το ρωτά συνέχεια — δηλαδή να μετρά χρόνο μόνη της. Και μόλις
     * μετρήσει χρόνο μόνη της, αποκτά δικούς της κανόνες, που αργά ή γρήγορα
     * διαφωνούν με τους εδώ.
     *
     * Ακριβώς αυτό είχε συμβεί: το `canDismiss` έλεγε «δεν υπάρχει μέγιστος
     * χρόνος», η οθόνη είχε ένα δεύτερο effect με χρονόμετρο 8 δευτερολέπτων, και
     * το policy δεν το ήξερε. Δύο απαντήσεις στην ίδια ερώτηση — και τα tests
     * φύλαγαν τη λάθος.
     *
     * Τώρα η οθόνη δεν αποφασίζει τίποτα: περιμένει όσο της πει και ξαναρωτά.
     */
    fun remainingMs(finished: Boolean, visibleMs: Long): Long {
        val untilMax = MAX_VISIBLE_MS - visibleMs
        // Το πάνω όριο υπερισχύει πάντα, ακόμη κι αν δεν έχει συμπληρωθεί το κάτω:
        // αν η φόρτωση κράτησε 8 δευτερόλεπτα, η οθόνη έχει ήδη ειπωθεί.
        if (untilMax <= 0L) return 0L
        if (!finished) return untilMax

        val untilSettled = MIN_VISIBLE_MS + SETTLE_MS - visibleMs
        return if (untilSettled <= 0L) 0L else minOf(untilSettled, untilMax)
    }
}
