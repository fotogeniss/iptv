package com.prelude.iptv.ui

import com.prelude.iptv.data.Channel
import com.prelude.iptv.data.ProviderMetadataPolicy

/**
 * Με ποια σειρά μπαίνουν τα «Νέα» και τα «Κορυφαία» στην αρχική.
 *
 * ΤΙ ΙΣΧΥΕ ΠΡΙΝ, και γιατί φαινόταν τυχαίο:
 *
 * - Τα «Κορυφαία» ήταν `unique(channels)` — **καμία ταξινόμηση**. Η σειρά του
 *   παρόχου, με νούμερα κατάταξης 1-20 τυπωμένα από πάνω. Η ράγα υποσχόταν
 *   κατάταξη που δεν υπήρχε.
 * - Τα «Νέα» ταξινομούνταν με `year`, αφού πρώτα κρατούσαν μόνο όσα είχαν
 *   `year.length == 4`. Ο πάροχος αυτού του καταλόγου στέλνει ολόκληρη
 *   ημερομηνία (`1993-08-28`, έντεκα χαρακτήρες), οπότε το φίλτρο τα έκοβε
 *   σχεδόν όλα. Και ακόμη κι όταν περνούσαν, το έτος παραγωγής δεν είναι
 *   «νέο»: μετράει πότε έγινε διαθέσιμο, όχι πότε γυρίστηκε.
 *
 * Οι συναρτήσεις εδώ είναι καθαρές και σταθερές (stable sort): με ίσα κριτήρια
 * διατηρείται η σειρά του παρόχου, ώστε η αρχική να μην αναδιατάσσεται μόνη της
 * ανάμεσα σε δύο ανανεώσεις.
 */
object CatalogRankingPolicy {

    /**
     * Βαθμολογία ως αριθμός, ή `null` όταν ο πάροχος δεν ξέρει.
     *
     * Πραγματικές τιμές στο ίδιο πεδίο: `"7"`, `"7.4"`, `"0"`, `""`, `"N/A"`.
     * Το μηδέν ΔΕΝ είναι βαθμολογία — είναι ο τρόπος που πολλά portals γράφουν
     * «δεν έχω». Αν το δεχόμασταν, οι αβαθμολόγητες ταινίες θα σχημάτιζαν μια
     * ψεύτικη ουρά στο τέλος της κατάταξης αντί να μείνουν εκτός.
     */
    fun ratingOf(channel: Channel): Double? =
        ProviderMetadataPolicy.text(channel.rating)
            .trim()
            .replace(',', '.')
            .toDoubleOrNull()
            ?.takeIf { it > 0.0 }

    /**
     * Πότε έγινε διαθέσιμο, ως συγκρίσιμο κείμενο· κενό όταν δεν ξέρουμε.
     *
     * Η μορφή του παρόχου (`2025-07-30 01:08:10`) συγκρίνεται σωστά
     * λεξικογραφικά επειδή είναι σταθερού πλάτους και από το μεγαλύτερο προς το
     * μικρότερο. Δεν γίνεται parsing σε ημερομηνία επίτηδες: θα απαιτούσε να
     * μαντέψουμε ζώνη ώρας και μορφή, και το μόνο που χρειάζεται εδώ είναι
     * σχετική σειρά, όχι πραγματικός χρόνος.
     */
    fun availabilityKeyOf(channel: Channel): String {
        val added = ProviderMetadataPolicy.text(channel.addedAt).trim()
        if (added.isNotBlank()) return added
        // Εφεδρεία για παρόχους που δεν στέλνουν «added»: το έτος, κανονικοποιημένο
        // ώστε ένα «1993-08-28» και ένα «1993» να συγκρίνονται μεταξύ τους.
        return ProviderMetadataPolicy.displayYear(channel.year)
    }

    /**
     * Τα πιο πρόσφατα πρώτα. Όσα δεν έχουν καμία ένδειξη χρόνου μένουν ΕΞΩ.
     *
     * Η αποβολή είναι σκόπιμη: μια ράγα «Νέα» που περιέχει στοιχεία αγνώστου
     * χρόνου δεν είναι λίστα νέων, είναι η ίδια η βιβλιοθήκη με άλλο τίτλο.
     */
    fun newestFirst(channels: List<Channel>): List<Channel> =
        channels
            .filter { availabilityKeyOf(it).isNotBlank() }
            .sortedByDescending(::availabilityKeyOf)

    /**
     * Οι υψηλότερες βαθμολογίες πρώτα. Όσα δεν έχουν βαθμολογία μένουν ΕΞΩ.
     *
     * Ίδιο σκεπτικό: η ράγα τυπώνει θέσεις 1, 2, 3. Ένα στοιχείο χωρίς
     * βαθμολογία δεν έχει θέση, και το να του δοθεί μία είναι απλώς ψέμα.
     */
    fun topRatedFirst(channels: List<Channel>): List<Channel> =
        channels
            .mapNotNull { channel -> ratingOf(channel)?.let { channel to it } }
            .sortedByDescending { it.second }
            .map { it.first }
}
