package com.prelude.iptv.ui.route

/**
 * Ιστορικό πλοήγησης ανάμεσα στις ενότητες του καταλόγου.
 *
 * ΤΟ ΠΡΟΒΛΗΜΑ ΠΟΥ ΛΥΝΕΙ: η τρέχουσα ενότητα ήταν ΜΙΑ μεταβλητή
 * (`mobilePrimaryDestination` / `tvSection`), όχι στοίβα. Κάθε μετάβαση
 * αντικαθιστούσε την προηγούμενη χωρίς να θυμάται από πού ήρθε ο χρήστης,
 * οπότε «πίσω» ανάμεσα σε ενότητες δεν υπήρχε καν ως έννοια — και ό,τι υπήρχε
 * ήταν σταθεροί προορισμοί: το βελάκι στα Ζωντανά πήγαινε ΠΑΝΤΑ στην Αρχική,
 * ακόμη κι αν ερχόσουν από τις Σειρές.
 *
 * ΓΙΑΤΙ ΚΑΘΑΡΗ ΠΟΛΙΤΙΚΗ: η πλοήγηση έχει ακριβώς το είδος σφαλμάτων που δεν
 * φαίνονται στη ζωγραφική αλλά μόνο σε ακολουθίες κινήσεων. Ίδιο σκεπτικό με
 * το [com.prelude.iptv.ui.tv.browse.TvLiveBrowsePolicy]: η απόφαση ζει εδώ και
 * δοκιμάζεται στη JVM, το Compose κρατά μόνο κατάσταση και focus.
 */
object SectionNavigationPolicy {

    /**
     * Πόσο βαθιά κρατάμε ιστορικό.
     *
     * Υπάρχουν τέσσερις ενότητες και η [open] καταρρέει τα διπλότυπα, οπότε στην
     * πράξη η στοίβα δεν ξεπερνά το τέσσερα. Το όριο είναι δικλείδα για να μη
     * μεγαλώνει απεριόριστα αν προστεθούν ενότητες αργότερα — μια στοίβα που
     * μεγαλώνει χωρίς φραγμό σημαίνει χρήστη που πατά «πίσω» δέκα φορές χωρίς
     * να βγαίνει πουθενά.
     */
    const val MAX_DEPTH = 8

    /** Η ενότητα στην οποία βρίσκεται ο χρήστης. */
    fun current(stack: List<String>): String = stack.lastOrNull().orEmpty()

    /** Υπάρχει κάπου να γυρίσει ο χρήστης μέσα στις ενότητες; */
    fun canGoBack(stack: List<String>): Boolean = stack.size > 1

    /**
     * Μετάβαση σε ενότητα.
     *
     * ΚΑΤΑΡΡΕΥΣΗ ΠΡΟΣ ΤΑ ΠΑΝΩ, ΟΧΙ ΤΥΦΛΟ PUSH. Αν η ενότητα υπάρχει ήδη πιο
     * κάτω στη στοίβα, κόβουμε ό,τι είναι πάνω της αντί να την ξαναπροσθέσουμε.
     * Αλλιώς η διαδρομή Αρχική → Ταινίες → Σειρές → Ταινίες θα απαιτούσε τρία
     * «πίσω» για να φτάσει στην Αρχική, περνώντας δεύτερη φορά από τις Σειρές —
     * κάτι που ο χρήστης βιώνει ως «με πάει κάπου αλλού». Είναι η ίδια
     * συμπεριφορά που έχει η κάτω μπάρα πλοήγησης του Android.
     *
     * Η ίδια ενότητα δύο φορές στη σειρά δεν αλλάζει τίποτα: το πάτημα της
     * ενότητας στην οποία ήδη βρίσκεσαι δεν είναι πλοήγηση.
     */
    fun open(stack: List<String>, section: String): List<String> {
        if (section.isBlank()) return stack
        if (stack.isEmpty()) return listOf(section)
        if (current(stack) == section) return stack
        val existing = stack.indexOf(section)
        if (existing >= 0) return stack.subList(0, existing + 1).toList()
        val grown = stack + section
        return if (grown.size <= MAX_DEPTH) grown else grown.takeLast(MAX_DEPTH)
    }

    /**
     * Ένα «πίσω» μέσα στις ενότητες.
     *
     * Επιστρέφει `null` στη ρίζα: εκεί η απόφαση ΔΕΝ ανήκει σε αυτή την
     * πολιτική, ανήκει στην από πάνω οθόνη (σήμερα: επιβεβαίωση αλλαγής πηγής).
     * Η ρητή διάκριση υπάρχει ώστε ο καλών να μην μπερδέψει το «γύρισα στην
     * Αρχική» με το «δεν έχω πού να γυρίσω».
     */
    fun back(stack: List<String>): List<String>? =
        if (canGoBack(stack)) stack.dropLast(1) else null

    /**
     * Συγχρονισμός όταν η ενότητα άλλαξε από αλλού.
     *
     * Ο τύπος περιεχομένου μπορεί να αλλάξει χωρίς πλοήγηση του χρήστη — από
     * επαναφορά κατάστασης ή από τη φόρτωση της πηγής. Αυτό ΔΕΝ πρέπει να
     * γράψει ιστορικό: αν το έκανε, ένα «πίσω» θα γύριζε σε ενότητα που ο
     * χρήστης δεν επισκέφθηκε ποτέ. Αντικαθιστά μόνο την κορυφή.
     */
    fun replaceTop(stack: List<String>, section: String): List<String> = when {
        section.isBlank() -> stack
        stack.isEmpty() -> listOf(section)
        current(stack) == section -> stack
        else -> stack.dropLast(1) + section
    }
}
