package com.prelude.iptv.player

/**
 * Τα ορίσματα με τα οποία ξεκινά το LibVLC.
 *
 * ΓΙΑΤΙ ΞΕΧΩΡΙΣΤΟ ΚΑΙ ΔΟΚΙΜΑΣΜΕΝΟ: είναι μια λίστα από κείμενα που πάει σε native
 * βιβλιοθήκη. Ένα ορθογραφικό λάθος **δεν δίνει σφάλμα** — το LibVLC αγνοεί ό,τι
 * δεν αναγνωρίζει και συνεχίζει με την προεπιλογή. Δηλαδή μια χαλασμένη ρύθμιση
 * μοιάζει ακριβώς με μια που δουλεύει, μέχρι να δεις τη διαφορά στην εικόνα.
 *
 * Εδώ τουλάχιστον καρφώνεται τι στέλνουμε, και γιατί.
 *
 * ---
 *
 * ΤΙ ΔΕΝ ΜΠΑΙΝΕΙ ΕΔΩ, ΕΠΙΤΗΔΕΣ:
 *
 * - **Επιτάχυνση υλικού.** Δεν είναι όρισμα εκκίνησης· ορίζεται ανά ροή με
 *   `Media.setHWDecoderEnabled(true, false)`. Το `force = false` αφήνει το LibVLC
 *   να πέσει σε λογισμικό όταν ο αποκωδικοποιητής της συσκευής αρνηθεί το προφίλ —
 *   συνηθισμένο σε HEVC 10-bit σε φθηνά TV box.
 * - **Passthrough AC-3 / Dolby.** Θέλει ξεχωριστή απόφαση ανά συσκευή και σιωπηλά
 *   δίνει βουβό ήχο όταν ο δέκτης δεν το υποστηρίζει. Το AC-3 αποκωδικοποιείται
 *   ούτως ή άλλως σε λογισμικό από το libavcodec που κουβαλά το LibVLC, οπότε
 *   **παίζει** — απλώς όχι bit-perfect προς τον δέκτη.
 */
object VlcOptionsPolicy {

    /**
     * Αποθήκευση δικτύου σε ms για ζωντανή ροή.
     *
     * 1500 και όχι 300: οι πάροχοι IPTV στέλνουν σε ριπές. Μικρό buffer σημαίνει
     * διακοπή σε κάθε ριπή· μεγάλο σημαίνει αργή αλλαγή καναλιού. Το 1,5 δευτ.
     * είναι το σημείο όπου η αλλαγή παραμένει γρήγορη και οι ριπές καλύπτονται.
     */
    const val LIVE_CACHING_MS = 1_500

    /** Ταινίες και επεισόδια: μεγαλύτερο, γιατί η αλλαγή δεν είναι συχνή. */
    const val VOD_CACHING_MS = 3_000

    /**
     * Τα ορίσματα εκκίνησης του LibVLC.
     *
     * @param live ζωντανή ροή (μικρότερη αποθήκευση, ανοχή σε ασυνέχειες)
     * @param verbose καταγραφή για διάγνωση· κλειστή σε release
     */
    fun startupOptions(live: Boolean, verbose: Boolean = false): List<String> {
        val caching = if (live) LIVE_CACHING_MS else VOD_CACHING_MS
        return buildList {
            // ---- αποθήκευση ----
            // Τέσσερις ξεχωριστές ρυθμίσεις γιατί το LibVLC έχει διαφορετικό
            // buffer ανά μεταφορά. Ορίζοντας μόνο το network-caching, το RTSP
            // κρατά τη δική του προεπιλογή και συμπεριφέρεται αλλιώς.
            add("--network-caching=$caching")
            add("--live-caching=$caching")
            add("--file-caching=$caching")
            add("--rtsp-caching=$caching")

            // ---- RTSP ----
            // Πάνω από TCP. Το UDP είναι ταχύτερο αλλά περνά μέσα από NAT και
            // firewall μόνο κατά τύχη — και όταν δεν περάσει, ο χρήστης βλέπει
            // μαύρη οθόνη χωρίς εξήγηση.
            add("--rtsp-tcp")

            // ---- HTTP ----
            // Επανασύνδεση όταν ο πάροχος κόψει τη σύνδεση, που στα IPTV είναι
            // κανόνας και όχι εξαίρεση.
            add("--http-reconnect")

            // ---- ρολόι ----
            // Οι ροές IPTV έχουν συχνά χαλασμένες χρονοσημάνσεις. Χωρίς αυτά, το
            // LibVLC προσπαθεί να συγχρονιστεί με ένα ρολόι που πηδά, και η
            // εικόνα «ρομποτίζει» — το ίδιο σύμπτωμα που κυνηγήσαμε στο Media3.
            add("--clock-jitter=0")
            add("--clock-synchro=0")

            // ---- ήχος ----
            // Κρατά τον τόνο σταθερό όταν αλλάζει η ταχύτητα αναπαραγωγής.
            add("--audio-time-stretch")

            // ---- υπότιτλοι ενσωματωμένοι ----
            // Οι ελληνικοί υπότιτλοι σε MPEG-TS είναι συχνά windows-1253 χωρίς
            // δήλωση. Το «auto» δοκιμάζει και δεν κολλά στο UTF-8.
            add("--subsdec-encoding=auto")

            // ---- διάγνωση ----
            if (verbose) add("-vv") else add("--quiet")
            add("--no-stats")
        }
    }

    /**
     * Πόσο επιθετικά παραλείπονται καρέ όταν η συσκευή δεν προλαβαίνει.
     *
     * 0 = τίποτα (σωστή εικόνα), 4 = τα πάντα (ρευστό αλλά άσχημο). Δίνεται
     * ξεχωριστά γιατί έχει νόημα μόνο σε αδύναμα TV box με HEVC, και εκεί είναι η
     * διαφορά ανάμεσα σε «παίζει» και «δεν παίζει».
     */
    fun skipLoopFilterOption(aggressive: Boolean): String =
        if (aggressive) "--avcodec-skiploopfilter=4" else "--avcodec-skiploopfilter=0"
}
